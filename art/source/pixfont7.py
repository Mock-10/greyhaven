H = 7
SPACE = 3
DIGITS = set('0123456789')


def glyph(ch):
    """The glyph's bit columns: proportional for letters and punctuation, full width for digits."""
    if ch == ' ':
        return np.zeros((H, SPACE), bool)
    rows = G.get(ch.upper(), G['?'])
    g = np.array([[c == '#' for c in r] for r in rows])
    if ch in DIGITS:
        return g
    used = np.nonzero(g.any(0))[0]
    return g[:, used.min():used.max() + 1]


def text_px(s):
    if not s:
        return np.zeros((H, 0), bool)
    cols = []
    for ch in s:
        cols.append(glyph(ch))
        cols.append(np.zeros((H, 1), bool))
    return np.concatenate(cols[:-1], 1)


def draw_text(img, x, y, s, color, shadow=None, scale=1):
    m = text_px(s)
    if scale != 1:
        m = np.kron(m, np.ones((scale, scale), bool))
    ys, xs = np.nonzero(m)
    Hh, W = img.shape[:2]
    for (dy, col) in (((1, shadow),) if shadow is not None else ()) + ((0, color),):
        for yy, xx in zip(ys + y + dy, xs + x):
            if 0 <= yy < Hh and 0 <= xx < W:
                img[yy, xx, :3] = col[:3]; img[yy, xx, 3] = 255
    return m.shape[1]


def text_width(s, scale=1):
    return text_px(s).shape[1] * scale


